// Build a small, GPU-independent explanation from the app's actual model.
import { build } from 'esbuild';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

mkdirSync('verification', { recursive: true });
const raw = 'artifacts/unit-tests.json';
let software;
if (existsSync(raw)) {
  const tests = JSON.parse(readFileSync(raw, 'utf8'));
  assert.equal(tests.success, true, 'Unit tests must pass before publishing their result');
  assert.equal(tests.numFailedTests, 0);
  software = { unitTests: tests.numPassedTests, failed: 0, runner: 'Vitest', scope: 'Automated software checks' };
  writeFileSync('verification/software.json', JSON.stringify(software, null, 2) + '\n');
} else if (existsSync('verification/software.json')) {
  software = JSON.parse(readFileSync('verification/software.json', 'utf8'));
} else {
  throw new Error('Run npm test before the first production build');
}

const compiled = await build({
  stdin: { contents: `
    import { seedHistory } from './src/app/emulation/seed.ts';
    import { assistanceForSession } from './src/core/assistance.ts';
    import { progressFor } from './src/core/records.ts';
    export function sample() {
      const records = seedHistory(21);
      return records.map((record, i) => {
        const history = records.slice(0, i + 1);
        const controls = assistanceForSession(history, record, 'left');
        return { day: i + 1, fingers: ['tam.index', 'tam.middle', 'tam.ring', 'tam.little'].map((id, f) => {
          const p = progressFor(history, 'left', id);
          return { name: ['Index', 'Middle', 'Ring', 'Little'][f], range: p.latest, baseline: p.baseline, margin: p.error.mdc, change: p.change, share: controls[f + 1].share };
        }) };
      });
    }
  `, resolveDir: process.cwd(), sourcefile: 'site-evidence.ts', loader: 'ts' },
  platform: 'node', format: 'esm', bundle: true, write: false,
});
const model = await import(`data:text/javascript;base64,${Buffer.from(compiled.outputFiles[0].text).toString('base64')}`);
const days = model.sample();
assert.equal(days.length, 21);
assert.ok(days.every((day) => day.fingers.every((finger) => Number.isFinite(finger.range) && Number.isFinite(finger.margin) && finger.share >= 0 && finger.share <= 1)));
const report = { simulated: true, description: 'Prepared sample history generated by the same simulation, assistance and progress functions used by the app. No participant outcomes.', software, days };
writeFileSync('dist/evidence-data.json', JSON.stringify(report));
console.log(`Public explanation: ${days.length} simulated visits; ${software.unitTests} passing software checks`);
