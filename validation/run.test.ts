const quick = process.env.VALIDATE_QUICK === '1';

function rms(values: number[]): number {
  const v = values.filter(Number.isFinite);
  return Math.sqrt(mean(v.map((x) => x * x)));
}

function sd(values: number[]): number {
  const v = values.filter(Number.isFinite);
  const m = mean(v);
  return Math.sqrt(v.reduce((s, x) => s + (x - m) ** 2, 0) / (v.length - 1));
}

const METRIC_KEYS = ['tam.index', 'tam.middle', 'tam.ring', 'tam.little', 'tam.total', 'opening', 'spread', 'kapandji'] as const;

function s2(noise: NoiseParams, users: number, sessions: number) {
  const perMetric: Record<string, number[]> = Object.fromEntries(METRIC_KEYS.map((k) => [k, []]));
  const estimatorRatio: number[] = [];
  for (let u = 0; u < users; u++) {
    const p = u % 2 === 0 ? healthyParams(100 + u) : randomPatient(100 + u, 'none');
    const tn = new TrackerNoise(noiseSeed(p, 0), noise);
    const series: Record<string, number[]> = Object.fromEntries(METRIC_KEYS.map((k) => [k, []]));
    const trialsTotal: number[][] = [];
    for (let s = 0; s < sessions; s++) {
      tn.newSession();
      const sp = simulateHandPrint(p, 'left', tn, 0, 5000 + u * 97 + s * 13);
      series['tam.index'].push(sp.value.tam[0]);
      series['tam.middle'].push(sp.value.tam[1]);
      series['tam.ring'].push(sp.value.tam[2]);
      series['tam.little'].push(sp.value.tam[3]);
      series['tam.total'].push(sp.value.tamTotal);
      series.opening.push(sp.value.opening);
      series.spread.push(sp.value.spread);
      series.kapandji.push(sp.value.kapandji);
      trialsTotal.push(sp.trials.map((t) => t.tamTotal));
    }
    for (const k of METRIC_KEYS) perMetric[k].push(sd(series[k]));
    // how well the in-app estimator recovers the true SEM from 10 sessions
    const trueSem = sd(series['tam.total']);
    const est = estimateError(trialsTotal.slice(0, 10), series['tam.total'].slice(0, 10), 1);
    estimatorRatio.push(est.sem / trueSem);
  }
  const sem = Object.fromEntries(METRIC_KEYS.map((k) => [k, rms(perMetric[k])]));
  const mdc = Object.fromEntries(METRIC_KEYS.map((k) => [k, 1.96 * Math.SQRT2 * (sem[k] as number)]));
  return { sem, mdc, estimatorToTrue: { median: median(estimatorRatio), min: Math.min(...estimatorRatio), max: Math.max(...estimatorRatio) } };
}

describe('simulated validation', () => {
  it('S2 test-retest error per Hand Print metric', () => {
    const users = quick ? 4 : 24;
    const sessions = quick ? 8 : 20;
    const main = s2(DEFAULT_NOISE, users, sessions);
    const low = s2({ ...DEFAULT_NOISE, sessionSigma: 3 }, quick ? 2 : 8, sessions);
    const high = s2({ ...DEFAULT_NOISE, sessionSigma: 9 }, quick ? 2 : 8, sessions);
    results.S2 = {
      users,
      sessions,
      default: main,
      sensitivity: { sessionSigma3: low.sem, sessionSigma9: high.sem },
    };
    for (const k of METRIC_KEYS) expect(Number.isFinite(main.sem[k] as number)).toBe(true);
    if (!quick) {
      const lines = METRIC_KEYS.map((k) => `  '${k}': ${(main.sem[k] as number).toFixed(3)},`).join('\n');
      writeFileSync(
        new URL('../src/core/priors.generated.ts', import.meta.url),
        `/**
 * Generated by validation/run.test.ts (S2). Do not edit by hand.
 * Standard error of a session value per Hand Print metric under the default
 * tracker error model, used until a user has five sessions of their own.
 */
export const SIMULATED_SEM: Record<string, number> = {
${lines}
};
`,
      );
    }
  });

  it('S3 hand-over follows recovery and ignores noise', () => {
    const perTrajectory = quick ? 6 : 50;
    const weeks = 8;
    const perWeek = 3;
    const trajectories: Trajectory[] = ['steady', 'plateau', 'none', 'relapse'];
    const tamMdc = ((results.S2 as any)?.default?.mdc?.['tam.index'] as number) ?? 30;
    const floor = 20;
    const summary: Record<string, unknown> = {};
    let flatMoves = 0;
    let flatSessions = 0;
    const steadyErrors: number[] = [];
    for (const traj of trajectories) {
      const moves: number[] = [];
      const finalErr: number[] = [];
      for (let i = 0; i < perTrajectory; i++) {
        const p = randomPatient(2000 + i + trajectories.indexOf(traj) * 1000, traj);
        const lead = healthyParams(p.seed + 1);
        const tnU = new TrackerNoise(noiseSeed(p, 0));
        const tnL = new TrackerNoise(noiseSeed(p, 1));
        const states = [0, 1, 2, 3].map(() => ({ anchorRange: NaN, share: 0 }));
        const history: number[][] = [[], [], [], []];
        let moved = 0;
        let sessionsAfterFirst = 0;
        let lastLead = [240, 240, 240, 240];
        for (let s = 0; s < weeks * perWeek; s++) {
          const week = s / perWeek;
          tnU.newSession();
          tnL.newSession();
          const own = simulateHandPrint(p, 'left', tnU, week, 9000 + i * 131 + s);
          if (s % perWeek === 0) lastLead = simulateHandPrint(lead, 'right', tnL, 0, 7000 + i * 131 + s).value.tam;
          for (let f = 0; f < 4; f++) {
            history[f].push(own.value.tam[f]);
            const rolling = median(history[f].slice(-3));
            const had = Number.isFinite(states[f].anchorRange);
            const changed = updateShare(states[f], rolling, lastLead[f], floor, tamMdc);
            if (had) {
              sessionsAfterFirst++;
              if (changed) moved++;
            }
          }
        }
        moves.push(moved / Math.max(1, sessionsAfterFirst));
        const truthOwn = trueTam(p, weeks);
        const truthLead = trueTam(lead, 0);
        for (let f = 0; f < 4; f++) {
          const truth = shareFromRange(truthOwn[f], truthLead[f], floor);
          finalErr.push(Math.abs(states[f].share - truth));
        }
        if (traj === 'none') {
          flatMoves += moved;
          flatSessions += sessionsAfterFirst;
        }
        if (traj === 'steady') steadyErrors.push(...finalErr);
      }
      summary[traj] = {
        patients: perTrajectory,
        moveRate: mean(moves),
        finalShareError: { median: median(finalErr), p90: [...finalErr].sort((a, b) => a - b)[Math.floor(finalErr.length * 0.9)] },
      };
    }
    const flatRate = flatMoves / Math.max(1, flatSessions);
    const steadyMedian = median(steadyErrors);
    results.S3 = { mdcUsed: tamMdc, floor, byTrajectory: summary, flatMoveRate: flatRate, steadyFinalErrorMedian: steadyMedian };
    results.S3_pass = { flatMoveRate: flatRate <= 0.02, steadyWithin015: steadyMedian <= 0.15 };
    expect(Number.isFinite(flatRate)).toBe(true);
  });

  it('S4 attempt gating (tuned on development seeds, scored on held-out seeds)', () => {
    const minutes = quick ? 2 : 10;
    const users = quick ? 3 : 10;
    const grid: { k: number; fast: number }[] = [];
    for (const fast of [0.12, 0.25, 0.4]) for (const k of [2.5, 3, 3.5, 4, 5]) grid.push({ k, fast });
    const dev = grid.map((g) => ({ ...g, ...evalDetector({ ...DEFAULT_ATTEMPT, ...g }, 3000, users, minutes, 5, false) }));
    // development budget with margin: <= 0.5 false attempts per minute per finger
    const eligible = dev.filter((d) => d.falsePerMin <= 0.5);
    const chosen = (eligible.length ? eligible : dev).reduce((a, b) => (b.detection > a.detection ? b : a));
    const cfg = { ...DEFAULT_ATTEMPT, k: chosen.k, fast: chosen.fast };
    const held = evalDetector(cfg, 13000, users, minutes, 5, false);
    // how detection grows with attempt size, per finger and whole hand
    const sizes = [5, 10, 15, 20];
    const bySize = sizes.map((size) => ({
      size,
      finger: evalDetector(cfg, 13000, users, 1, size, false).detection,
      wholeHand: evalDetector(cfg, 13000, users, 1, size, true).detection,
    }));
    const wholeHand5 = evalDetector(cfg, 13000, users, minutes, 5, true);
    results.S4 = {
      attemptDefinition: 'summed MCP+PIP+DIP flexion of one finger, ramped over 0.6 s, held 0.6 s',
      development: dev,
      chosen: { k: chosen.k, fast: chosen.fast },
      shipped: { k: DEFAULT_ATTEMPT.k, fast: DEFAULT_ATTEMPT.fast },
      heldOut: held,
      heldOutBySize: bySize,
      heldOutWholeHand5: wholeHand5,
      users,
      minutes,
    };
    results.S4_pass = {
      falseRate: held.falsePerMin <= 1,
      detection: held.detection >= 0.9,
      wholeHandFalseRate: wholeHand5.falsePerMin <= 1,
      wholeHandDetection: wholeHand5.detection >= 0.9,
      shippedMatchesChosen: chosen.k === DEFAULT_ATTEMPT.k && chosen.fast === DEFAULT_ATTEMPT.fast,
    };
    expect(Number.isFinite(held.detection)).toBe(true);
  });

  it('S5 warm-up stiffness recovery', () => {
    const n = quick ? 20 : 200;
    const truth: number[] = [];
    const est: number[] = [];
    for (let i = 0; i < n; i++) {
      const r = rng(5000 + i);
      const p = i % 2 ? healthyParams(6000 + i) : randomPatient(6000 + i, 'none');
      const tn = new TrackerNoise(noiseSeed(p, 0));
      const stiffness = r() * 0.4;
      const tau = 1 + r() * 3;
      const ranges = simulateWarmup(p, 'left', tn, stiffness, tau, 8000 + i * 11);
      const fit = fitWarmup(ranges);
      // ground truth: the share of the plateau range missing on repetition 1
      const plateau = trueTam(p, 0).reduce((a, b) => a + b, 0);
      truth.push(stiffness * plateau);
      est.push(fit ? fit.plateau - fit.first : NaN);
    }
    const rho = spearman(truth, est.map((x) => (Number.isFinite(x) ? x : 0)));
    results.S5 = { curves: n, spearman: rho };
    results.S5_pass = { spearman: rho >= 0.9 };
    expect(Number.isFinite(rho)).toBe(true);
  });

  it('S11 replays are deterministic', () => {
    const run = () => {
      const p = randomPatient(77, 'steady');
      const tn = new TrackerNoise(noiseSeed(p, 0));
      return JSON.stringify(simulateHandPrint(p, 'left', tn, 3, 1234).value);
    };
    const a = run();
    const b = run();
    results.S11 = { identical: a === b };
    expect(a).toBe(b);
    writeFileSync(new URL('./results.json', import.meta.url), JSON.stringify(results, null, 2));
  });
});

function evalDetector(cfg: typeof DEFAULT_ATTEMPT, seedBase: number, users: number, minutes: number, sizeDeg: number, wholeHand: boolean) {
  const dt = 1 / FPS;
  // still Understudy fingers while the Lead hand moves continuously
  let falseOnsets = 0;
  for (let u = 0; u < users; u++) {
    const p = randomPatient(seedBase + u, 'none');
    const tn = new TrackerNoise(noiseSeed(p, 0));
    const channels = wholeHand ? [-1] : [0, 1, 2, 3];
    const dets = channels.map(() => new FingerAttemptDetector(cfg));
    const leads = channels.map(() => new LeadMotion());
    const rest = patientRest(p);
    const noisy = neutralAngles();
    const signal = (f: number) => (f < 0 ? handSum(noisy) : sum(noisy, f));
    for (let i = 0; i < 10 * FPS; i++) {
      const ok = tn.apply(rest, dt, noisy);
      dets.forEach((d, i2) => ok && d.calibrate(signal(channels[i2]), dt));
    }
    dets.forEach((d) => d.finishCalibration());
    for (let i = 0; i < minutes * 60 * FPS; i++) {
      const t = i * dt;
      const leadAngle = 80 + 70 * Math.sin(2 * Math.PI * 0.4 * t);
      const ok = tn.apply(rest, dt, noisy);
      dets.forEach((d, i2) => {
        leads[i2].update(leadAngle, dt);
        if (ok) d.update(signal(channels[i2]), dt, leads[i2].velocity, leads[i2].moving);
      });
    }
    falseOnsets += dets.reduce((s, d) => s + d.onsets, 0);
  }
  const falsePerMin = falseOnsets / (users * (wholeHand ? 1 : 4) * minutes);

  // 5 degree attempts timed with the Lead's closing phase
  let detected = 0;
  let attempts = 0;
  for (let u = 0; u < users; u++) {
    const p = randomPatient(seedBase + 500 + u, 'none');
    const tn = new TrackerNoise(noiseSeed(p, 0));
    const det = new FingerAttemptDetector(cfg);
    const lead = new LeadMotion();
    const rest = patientRest(p);
    const noisy = neutralAngles();
    for (let i = 0; i < 10 * FPS; i++) {
      const ok = tn.apply(rest, dt, noisy);
      if (ok) det.calibrate(wholeHand ? handSum(noisy) : sum(noisy, 0), dt);
    }
    det.finishCalibration();
    const cur = neutralAngles();
    const period = 3;
    const n = Math.round((minutes * 30) / period);
    for (let a = 0; a < n; a++) {
      let hit = false;
      for (let i = 0; i < period * FPS; i++) {
        const t = i * dt;
        // Lead closes over 0.6 s, holds, opens; the Understudy tries 5 degrees
        const leadAngle = t < 0.6 ? 40 + 120 * (t / 0.6) : t < 1.4 ? 160 : t < 2.0 ? 160 - 120 * ((t - 1.4) / 0.6) : 40;
        const effort = t < 0.2 ? 0 : t < 0.8 ? (t - 0.2) / 0.6 : t < 1.4 ? 1 : t < 2.0 ? 1 - (t - 1.4) / 0.6 : 0;
        lerpAngles(rest, rest, 0, cur);
        // the attempt is spread over MCP, PIP and DIP (0.5 / 0.3 / 0.2)
        const moved = wholeHand ? [0, 1, 2, 3] : [0];
        for (const f of moved) {
          cur.fingers[f].mcpFlex = rest.fingers[f].mcpFlex + 0.5 * sizeDeg * effort;
          cur.fingers[f].pipFlex = rest.fingers[f].pipFlex + 0.3 * sizeDeg * effort;
          cur.fingers[f].dipFlex = rest.fingers[f].dipFlex + 0.2 * sizeDeg * effort;
        }
        lead.update(leadAngle, dt);
        const ok = tn.apply(cur, dt, noisy);
        if (ok) det.update(wholeHand ? handSum(noisy) : sum(noisy, 0), dt, lead.velocity, lead.moving);
        if (t < 1.6 && det.active) hit = true;
      }
      attempts++;
      if (hit) detected++;
    }
  }
  return { falsePerMin, detection: detected / attempts };
}

/** Whole-hand flexion scaled to one finger's units, so thresholds are comparable. */
function handSum(a: ReturnType<typeof neutralAngles>): number {
  return (sum(a, 0) + sum(a, 1) + sum(a, 2) + sum(a, 3)) / 4;
}

function sum(a: ReturnType<typeof neutralAngles>, f: number): number {
  const x = a.fingers[f];
  return x.mcpFlex + x.pipFlex + x.dipFlex;
}

